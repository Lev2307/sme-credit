from decimal import Decimal


def annuity_payment(amount: Decimal, annual_rate: Decimal, months: int) -> Decimal:
    """Ежемесячный платёж по аннуитетному кредиту (каждый месяц одинаковая сумма).

    amount       — сумма кредита в рублях, например Decimal("1000000")
    annual_rate  — годовая ставка в процентах, например Decimal("12") — это 12% годовых
    months       — срок в месяцах

    Формула аннуитета: P = S · r / (1 − (1 + r)^−n),
    где S — сумма, r — ставка за месяц в долях, n — число месяцев.

    Пример: 1 000 000 ₽ под 12% на 12 месяцев → 88 848,79 ₽ в месяц.
    """
    # Годовые проценты → месячная ставка в долях: 12% / 100 / 12 = 0.01
    r = annual_rate / 100 / 12

    # При нулевой ставке формула делит на ноль (1 − 1^−n = 0),
    # а платёж — просто сумма, поделённая на месяцы
    if r == 0:
        return (amount / months).quantize(Decimal("0.01"))

    payment = amount * r / (1 - (1 + r) ** -months)

    # Округляем до копеек. quantize без параметров округляет «по-банковски»: ровно половину копейки — к чётному.
    return payment.quantize(Decimal("0.01"))